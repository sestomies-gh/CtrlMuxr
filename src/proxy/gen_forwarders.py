"""Generates linker export-forwarder headers for a system DLL, so a proxy of the same name can forward every export
to the real DLL by absolute path (no thunk code, works for named exports).
Usage: py gen_forwarders.py msacm32     -> msacm32_fwd_x86.h, msacm32_fwd_x64.h
Needs the MSVC build tools (dumpbin) like build.bat."""
import os
import re
import subprocess
import sys
import tempfile

VC = r'C:\Program Files (x86)\Microsoft Visual Studio\18\BuildTools\VC\Auxiliary\Build'
ARCHS = {
    'x86': (r'C:\Windows\SysWOW64', 'vcvars32.bat'),
    'x64': (r'C:\Windows\System32', 'vcvars64.bat'),
}

dll = sys.argv[1].lower()
for arch, (sysdir, vc) in ARCHS.items():
    path = sysdir + '\\' + dll + '.dll'
    bat = os.path.join(tempfile.gettempdir(), 'gen_fwd_%s.bat' % arch)      # a .bat avoids cmd /c quoting problems
    with open(bat, 'w') as bf:
        bf.write('@echo off\r\ncall "%s\\%s" >nul 2>&1\r\ndumpbin /exports "%s"\r\n' % (VC, vc, path))
    out = subprocess.run(['cmd', '/c', bat], capture_output=True, text=True).stdout
    lines = []
    anon = 0
    for m in re.finditer(r'^\s+(\d+)\s+[0-9A-F]+\s+(?:[0-9A-F]{8}\s+)?(\S+)(?:\s+=.*)?$', out, re.M):
        ordinal, name = m.group(1), m.group(2)
        if re.fullmatch(r'[0-9A-F]{8}', name):       # ordinal-only export (no name column)
            anon += 1
            continue
        target = (sysdir + '\\' + dll).replace('\\', '\\\\')
        lines.append('#pragma comment(linker, "/export:%s=%s.%s,@%s")' % (name, target, name, ordinal))
    with open('%s_fwd_%s.h' % (dll, arch), 'w') as f:
        f.write('// generated by gen_forwarders.py from %s\n' % path)
        f.write('\n'.join(lines) + '\n')
    print(arch, len(lines), 'forwarders', ('(%d ordinal-only skipped)' % anon) if anon else '')
